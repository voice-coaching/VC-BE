-- Existing encrypted originals remain private. Library membership protects them from history-only cleanup.
CREATE UNIQUE INDEX uq_practice_content_owner ON practice_contents(id,owner_id);
CREATE TABLE script_library_topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name_ciphertext TEXT NOT NULL,
    name_digest VARCHAR(64) NOT NULL,
    CONSTRAINT uq_script_topic_owner UNIQUE(id,user_id),
    CONSTRAINT uq_script_topic_name UNIQUE(user_id,name_digest)
);
CREATE TABLE script_library_entries (
    content_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    topic_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_script_content_owner FOREIGN KEY(content_id,user_id) REFERENCES practice_contents(id,owner_id),
    CONSTRAINT fk_script_topic_owner FOREIGN KEY(topic_id,user_id) REFERENCES script_library_topics(id,user_id)
);
CREATE INDEX idx_script_library_user ON script_library_entries(user_id,created_at DESC,content_id DESC);
CREATE INDEX idx_script_library_topic ON script_library_entries(topic_id,user_id);
CREATE TABLE script_library_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest VARCHAR(64) NOT NULL,
    request_digest VARCHAR(64) NOT NULL,
    content_id BIGINT NOT NULL,
    CONSTRAINT uq_script_library_request UNIQUE(user_id,key_digest),
    CONSTRAINT fk_script_request_owner FOREIGN KEY(content_id,user_id) REFERENCES practice_contents(id,owner_id)
);
-- Recover previously entered originals without copying their encrypted text or exposing public content.
INSERT INTO script_library_entries(content_id,user_id,created_at)
SELECT id,owner_id,created_at FROM practice_contents WHERE owner_id IS NOT NULL AND custom_deleted_at IS NULL;
