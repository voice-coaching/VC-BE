CREATE FUNCTION prevent_example_content_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS(SELECT 1 FROM practice_examples WHERE content_id=OLD.id) AND
        (NEW.script_text IS DISTINCT FROM OLD.script_text OR NEW.title IS DISTINCT FROM OLD.title OR NEW.owner_id IS DISTINCT FROM OLD.owner_id
         OR NEW.content_type IS DISTINCT FROM OLD.content_type OR NEW.custom_script_ciphertext IS DISTINCT FROM OLD.custom_script_ciphertext OR NEW.custom_title_ciphertext IS DISTINCT FROM OLD.custom_title_ciphertext) THEN
        RAISE EXCEPTION 'Example content is immutable; publish a new revision' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER example_content_immutable BEFORE UPDATE ON practice_contents FOR EACH ROW EXECUTE FUNCTION prevent_example_content_mutation();
