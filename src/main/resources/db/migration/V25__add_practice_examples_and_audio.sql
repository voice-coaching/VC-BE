CREATE FUNCTION validate_practice_example_set() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target BIGINT;
BEGIN
    IF TG_TABLE_NAME='practice_example_sets' THEN target := NEW.id; ELSE target := NEW.set_id; END IF;
    IF (SELECT count(*) FROM practice_examples WHERE set_id=target)<>5 THEN
        RAISE EXCEPTION 'A published example revision requires exactly five items' USING ERRCODE='23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM practice_example_sets s JOIN course_step_revisions r ON r.id=s.education_revision_id AND r.step_id=s.step_id WHERE s.id=target) THEN
        RAISE EXCEPTION 'Example and education step mismatch' USING ERRCODE='23514';
    END IF;
    IF EXISTS (SELECT 1 FROM practice_examples e JOIN practice_contents c ON c.id=e.content_id WHERE e.set_id=target AND
        (c.owner_id IS NOT NULL OR c.content_type<>'CLASS_PRACTICE' OR c.status<>'PUBLISHED' OR length(trim(c.script_text))=0 OR octet_length(c.script_text)>4500)) THEN
        RAISE EXCEPTION 'Invalid published example content' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER example_set_complete AFTER INSERT ON practice_example_sets DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION validate_practice_example_set();
CREATE CONSTRAINT TRIGGER example_items_complete AFTER INSERT ON practice_examples DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION validate_practice_example_set();
