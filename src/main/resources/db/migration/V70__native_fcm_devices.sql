CREATE TABLE native_fcm_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    installation_id UUID NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    encrypted_token TEXT NOT NULL,
    platform VARCHAR(10) NOT NULL CHECK (platform = 'ANDROID'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_native_fcm_installation UNIQUE(user_id, installation_id)
);
CREATE INDEX idx_native_fcm_devices_user ON native_fcm_devices(user_id);

CREATE TABLE native_fcm_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES user_notifications(id) ON DELETE CASCADE,
    device_id BIGINT NOT NULL REFERENCES native_fcm_devices(id) ON DELETE CASCADE,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING','SENDING','SENT','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_until TIMESTAMPTZ,
    lease_id UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(notification_id, device_id)
);
CREATE INDEX idx_native_fcm_outbox_due ON native_fcm_outbox(available_at, id) WHERE state IN ('PENDING','SENDING');

CREATE FUNCTION enqueue_native_fcm_notification() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO native_fcm_outbox(notification_id, device_id)
        SELECT NEW.id, d.id FROM native_fcm_devices d WHERE d.user_id = NEW.user_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER enqueue_native_fcm AFTER INSERT ON user_notifications
    FOR EACH ROW EXECUTE FUNCTION enqueue_native_fcm_notification();
