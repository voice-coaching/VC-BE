CREATE TABLE title_policies (
    target_rank VARCHAR(30) PRIMARY KEY,
    required_training_count BIGINT NOT NULL CHECK (required_training_count >= 0),
    passing_score INTEGER NOT NULL CHECK (passing_score BETWEEN 0 AND 100),
    practice_content_id BIGINT REFERENCES practice_contents(id)
);
