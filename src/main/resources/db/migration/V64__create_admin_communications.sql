-- App inbox delivery only. No external push, email or automatic payment events.
CREATE TABLE admin_notification_campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    audience VARCHAR(20) NOT NULL CHECK (audience IN ('ALL_ACTIVE','SELECTED_USERS')),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('GENERAL','PLAN')),
    title VARCHAR(200) NOT NULL CHECK (length(trim(title))>0),
    body VARCHAR(1000) NOT NULL CHECK (length(trim(body))>0),
    deep_link VARCHAR(255) NOT NULL CHECK (deep_link IN ('/home','/notifications','/mypage')),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    sent_at TIMESTAMPTZ,
    sent_count BIGINT NOT NULL DEFAULT 0 CHECK (sent_count>=0),
    CHECK (sent_at IS NOT NULL OR sent_count=0)
);
CREATE TABLE admin_notification_recipients (
    campaign_id BIGINT NOT NULL REFERENCES admin_notification_campaigns(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (campaign_id,user_id)
);
CREATE TABLE admin_popups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title))>0),
    body VARCHAR(1000) NOT NULL CHECK (length(trim(body))>0),
    deep_link VARCHAR(255) CHECK (deep_link IN ('/home','/notifications','/mypage')),
    priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 100),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    CHECK (ends_at>starts_at AND ends_at<=starts_at+INTERVAL '365 days')
);
CREATE INDEX ix_admin_popups_active ON admin_popups (priority DESC, starts_at DESC, id DESC) WHERE enabled;
